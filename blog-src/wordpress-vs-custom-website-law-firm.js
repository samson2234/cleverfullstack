<p>Most WordPress problems come from how a site is built and looked after, not from WordPress itself.</p>
<ul>
  <li><strong>Security.</strong> WordPress is a common target because it is so popular. Outdated plugins are the usual way in. A firm site needs regular updates, strong logins, backups and a security plugin or firewall. Clients trust you with sensitive matters, so a hacked site does real damage.</li>
