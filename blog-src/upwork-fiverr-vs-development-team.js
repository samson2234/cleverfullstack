<p>If you need something built, the marketplaces are the obvious first stop. Thousands of developers, ratings on every profile, and prices that look lower than any agency's. Many businesses get great results there. Many others end up paying twice: once for the first attempt, and again to have it fixed or rebuilt.</p>
